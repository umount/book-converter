//! Построение промптов для перевода.
//!
//! Промпт собирается динамически: базовые инструкции + релевантные термины
//! глоссария (обязательный словарь) + опциональное резюме предыдущей главы.
//! Именно подстановка глоссария обеспечивает единообразие имён/терминов.

use crate::config::Config;
use crate::glossary::Term;

/// System-промпт: роль и общие правила перевода.
pub fn system_prompt(config: &Config) -> String {
    format!(
        "Ты — профессиональный литературный переводчик с {src} на {tgt}. \
         Переводи художественно и связно, сохраняя стиль и абзацы. \
         Не добавляй пояснений и примечаний — только перевод.",
        src = config.source_lang,
        tgt = config.target_lang,
    )
}

