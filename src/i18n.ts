const messages: Record<Lang, Dict> = { en, ru, zh };

export const LS_LANG = "bc.lang";

export function normalizeLang(v: string | null): Lang {
  return v === "ru" || v === "zh" || v === "en" ? v : "en";
}

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const raw = messages[lang]?.[key] ?? en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}
